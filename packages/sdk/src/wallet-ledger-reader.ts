import { toCAIP2Network, type Session, type TokenHoldingRef, type TxReceipt } from '@partylayer/core';

/** The authenticated wallet owns transport and authorization. No participant credentials are accepted. */
export interface WalletLedgerClient {
  getActiveSession(): Promise<Session | null>;
  asProvider(): { request<T = unknown>(args: { method: string; params?: unknown }): Promise<T> };
}

export interface WalletLedgerReaderOptions {
  /** Explicit expected CAIP-2 network. Never infer a network from an update id. */
  networkId: string;
  /** Exact package-id-qualified HoldingV1 interface id from the asset deployment. */
  holdingInterfaceId?: string;
  /** Default 30s; applies to the complete read, including session checks. */
  timeoutMs?: number;
  /** Reject snapshots at this boundary rather than display potentially incomplete balances. Default 1000. */
  maxContracts?: number;
}

export interface WalletHoldingsSnapshot {
  walletId: string;
  partyId: string;
  networkId: string;
  offset: number;
  holdings: TokenHoldingRef[];
}

export interface WalletTransactionReference {
  walletId: string;
  partyId: string;
  networkId: string;
  /** Original command id generated by the app BEFORE submission, not copied from an untrusted receipt. */
  commandId?: string;
  receipt?: TxReceipt;
  updateId?: string;
}

export type WalletTransactionConfirmation =
  | { status: 'confirmed'; updateId: string }
  | { status: 'unknown'; reason: string };

type Json = Record<string, unknown>;
function object(value: unknown): Json {
  if (!value || typeof value !== 'object' || Array.isArray(value)) throw new Error('Malformed Ledger API response');
  return value as Json;
}
function text(value: unknown): string {
  if (typeof value !== 'string' || !value || value.length > 2048 || /\p{Cc}/u.test(value)) {
    throw new Error('Invalid Ledger API identifier');
  }
  return value;
}
const identity = (s: Session) => JSON.stringify([s.sessionId, s.walletId, s.partyId, toCAIP2Network(s.network).networkId]);

/**
 * Read-only JSON Ledger API v2 adapter using CIP-0103 ledgerApi. Uses eventFormat
 * and update-by-id (not the removed transaction-by-id endpoint). A wallet may
 * restrict these endpoints; errors remain errors, never empty balances/success.
 */
export function createWalletLedgerReader(client: WalletLedgerClient, options: WalletLedgerReaderOptions) {
  return createScopedLedgerReader(client, options);
}

/** Internal transport seam; only the two reviewed read-only transports expose it. */
export function createScopedLedgerReader(client: WalletLedgerClient, options: WalletLedgerReaderOptions,
  applicationRequest?: (session: Session, resource: string, body: Json | undefined, signal: AbortSignal) => Promise<unknown>) {
  const networkId = text(options.networkId);
  if (!/^canton:[a-zA-Z0-9_-]+$/.test(networkId)) throw new Error('Expected a Canton CAIP-2 network id');
  const interfaceId = options.holdingInterfaceId === undefined ? undefined : text(options.holdingInterfaceId);
  if (interfaceId && !/^[^:#\s]+:[^:\s]+:[^:\s]+$/.test(interfaceId)) throw new Error('Use an exact package-id-qualified holding interface id');
  const timeoutMs = options.timeoutMs ?? 30_000;
  const maxContracts = options.maxContracts ?? 1000;
  if (!Number.isInteger(timeoutMs) || timeoutMs < 1 || timeoutMs > 300_000) throw new Error('Invalid ledger read timeout');
  if (!Number.isInteger(maxContracts) || maxContracts < 1 || maxContracts > 10_000) throw new Error('Invalid snapshot limit');

  async function read<T>(signal: AbortSignal | undefined, action: (session: Session, request: (resource: string, body?: Json) => Promise<unknown>) => Promise<T>): Promise<T> {
    let timer: ReturnType<typeof setTimeout> | undefined;
    let stop: (() => void) | undefined;
    let stopped = false;
    const controller = new AbortController();
    const aborted = new Promise<never>((_resolve, reject) => {
      stop = () => { stopped = true; controller.abort(); reject(new Error('Ledger read cancelled or timed out')); };
      if (signal?.aborted) stop();
      else signal?.addEventListener('abort', stop, { once: true });
      timer = setTimeout(stop, timeoutMs);
    });
    const run = async () => {
      const session = await client.getActiveSession();
      if (stopped) throw new Error('Ledger read cancelled');
      if (!session || session.networkMismatch || toCAIP2Network(session.network).networkId !== networkId) {
        throw new Error('Connect a wallet on the expected network before reading the ledger');
      }
      if (!applicationRequest && !session.capabilitiesSnapshot.includes('ledgerApi')) throw new Error('This wallet does not expose ledgerApi');
      const captured = identity(session);
      const assertCurrent = async () => {
        const current = await client.getActiveSession();
        if (stopped || !current || current.networkMismatch || identity(current) !== captured) throw new Error('Wallet session changed during ledger read');
      };
      const request = async (resource: string, body?: Json) => {
        await assertCurrent();
        let result: unknown = applicationRequest ? await applicationRequest(session, resource, body, controller.signal) : await client.asProvider().request({ method: 'ledgerApi', params: {
          requestMethod: body ? 'post' : 'get', resource, ...(body ? { body } : {}),
        } });
        await assertCurrent();
        // The legacy PartyLayer bridge wraps JSON in {response: string}; native
        // CIP-0103 returns the JSON value directly. Do not accept other envelopes.
        if (result && typeof result === 'object' && !Array.isArray(result) &&
          Object.keys(result).length === 1 && typeof (result as Json).response === 'string') result = (result as Json).response;
        if (typeof result === 'string') {
          if (result.length > 8_000_000) throw new Error('Ledger response is too large');
          result = JSON.parse(result);
        }
        return result;
      };
      const result = await action(session, request);
      await assertCurrent();
      return result;
    };
    try { return await Promise.race([run(), aborted]); }
    finally { if (timer) clearTimeout(timer); if (stop) signal?.removeEventListener('abort', stop); }
  }

  return {
    /** A bounded, complete ACS snapshot of the connected party's configured HoldingV1 interface. */
    readHoldings(signal?: AbortSignal): Promise<WalletHoldingsSnapshot> {
      return read(signal, async (session, request) => {
        if (!interfaceId) throw new Error('Configure holdingInterfaceId before reading holdings');
        const end = object(await request('/v2/state/ledger-end'));
        if (!Number.isSafeInteger(end.offset) || (end.offset as number) < 0) throw new Error('Unsafe or invalid ledger offset');
        const rows = await request('/v2/state/active-contracts', {
          activeAtOffset: end.offset,
          eventFormat: { filtersByParty: { [String(session.partyId)]: { cumulative: [{
            identifierFilter: { InterfaceFilter: { value: { interfaceId, includeInterfaceView: true } } },
          }] } }, verbose: false },
        });
        if (!Array.isArray(rows) || rows.length >= maxContracts) throw new Error('Incomplete or oversized holdings snapshot');
        const seen = new Set<string>();
        const holdings = rows.map(row => {
          const entry = object(object(row).contractEntry);
          if (Object.keys(entry).length !== 1 || !entry.JsActiveContract) throw new Error('Snapshot contains an incomplete reassignment');
          const created = object(object(entry.JsActiveContract).createdEvent);
          const cid = text(created.contractId);
          if (seen.has(cid)) throw new Error('Duplicate holding contract in snapshot');
          seen.add(cid);
          if (!Array.isArray(created.interfaceViews)) throw new Error('Missing holding interface view');
          const views = created.interfaceViews.filter(v => object(v).interfaceId === interfaceId);
          if (views.length !== 1) throw new Error('Missing or ambiguous holding interface view');
          const view = object(views[0]);
          if (object(view.viewStatus).code !== 0) throw new Error('Holding interface view failed');
          const value = object(view.viewValue);
          if (value.owner !== String(session.partyId)) throw new Error('Holding belongs to another party');
          const instrument = object(value.instrumentId);
          if (typeof value.amount !== 'string' || !/^(?:0|[1-9]\d{0,27})(?:\.\d{1,10})?$/.test(value.amount)) throw new Error('Invalid token decimal');
          // Preserve unknown lock/metadata fields through strict validation;
          // a locked token must never become spendable because of a parser fallback.
          let lock: TokenHoldingRef['holding']['lock'];
          if (value.lock !== null && value.lock !== undefined) {
            const raw = object(value.lock);
            if (!Array.isArray(raw.holders)) throw new Error('Invalid holding lock');
            lock = { holders: raw.holders.map(text) };
            for (const key of ['expiresAt', 'expiresAfter', 'context'] as const) {
              if (raw[key] !== undefined && raw[key] !== null) lock[key] = text(raw[key]);
            }
          }
          let meta: Record<string, string> | undefined;
          if (value.meta !== undefined && value.meta !== null) {
            const raw = object(value.meta);
            // Token-standard Metadata wraps a TextMap in `values`.
            const values = Object.hasOwn(raw, 'values') ? object(raw.values) : raw;
            if (Object.values(values).some(v => typeof v !== 'string')) throw new Error('Invalid holding metadata');
            meta = { ...values } as Record<string, string>;
          }
          return { cid, holding: { owner: String(session.partyId), instrumentId: { admin: text(instrument.admin), id: text(instrument.id) },
            amount: value.amount, ...(lock ? { lock } : {}), ...(meta ? { meta } : {}) } };
        });
        return { walletId: String(session.walletId), partyId: String(session.partyId), networkId, offset: end.offset as number, holdings };
      });
    },

    /** One read, never polling or resubmission. Unknown remains unknown if ids cannot be correlated. */
    async confirmTransaction({ transaction, signal }: { transaction: WalletTransactionReference; signal?: AbortSignal }): Promise<WalletTransactionConfirmation> {
      const updateId = transaction.receipt?.updateId ?? transaction.updateId;
      if (!updateId || !transaction.commandId) return { status: 'unknown', reason: 'An update id and the original app command id are required' };
      if (transaction.receipt?.commandId && transaction.receipt.commandId !== transaction.commandId) {
        return { status: 'unknown', reason: 'Wallet receipt conflicts with the original command id' };
      }
      text(updateId); text(transaction.commandId);
      return read(signal, async (session, request) => {
        if (transaction.networkId !== networkId || transaction.partyId !== String(session.partyId) || transaction.walletId !== String(session.walletId)) {
          throw new Error('Transaction does not belong to the connected wallet account and network');
        }
        if (transaction.updateId && transaction.updateId !== updateId) throw new Error('Conflicting update ids');
        const result = object(await request('/v2/updates/update-by-id', { updateId,
          updateFormat: { includeTransactions: { eventFormat: { filtersByParty: { [String(session.partyId)]: {} }, verbose: false },
            transactionShape: 'TRANSACTION_SHAPE_ACS_DELTA' } },
        }));
        const update = object(result.update);
        if (Object.keys(update).length !== 1 || !update.Transaction) throw new Error('Requested update is not a transaction');
        const tx = object(object(update.Transaction).value);
        if (tx.updateId !== updateId || tx.commandId !== transaction.commandId || !Array.isArray(tx.events)) {
          return { status: 'unknown', reason: 'Ledger transaction cannot be correlated with the original command' };
        }
        return { status: 'confirmed', updateId };
      });
    },
  };
}

export type WalletLedgerReader = ReturnType<typeof createWalletLedgerReader>;
